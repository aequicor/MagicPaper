package io.aequicor.magicpaper.data.skills

import io.aequicor.magicpaper.domain.CatalogEntry
import io.aequicor.magicpaper.domain.SkillCatalog
import io.aequicor.magicpaper.util.TextSimilarity

/**
 * Встроенная лавка навыков: каталог проверенных позиций живёт в коде,
 * доступен офлайн и не зависит от внешних реестров (как встроенная
 * документация, только для скиллов). Каталог — источник «задач со стажем»;
 * самодельные навыки агента живут отдельно (см. Skills).
 */
class EmbeddedSkillCatalog : SkillCatalog {

    private val entries: List<CatalogEntry> = buildEntries()

    override suspend fun entries(): List<CatalogEntry> = entries

    override suspend fun search(query: String, limit: Int): List<CatalogEntry> {
        if (query.isBlank()) return entries.take(limit)
        return entries
            .map { it to TextSimilarity.score(query, it.name + " " + it.description + " " + it.tags.joinToString(" ")) }
            .filter { it.second > 0.0 }
            .sortedByDescending { it.second }
            .take(limit)
            .map { it.first }
    }

